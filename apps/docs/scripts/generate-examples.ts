/**
 * Compiles every documentation example with the real compiler and writes what it produced, so the
 * CSS, class names and diagnostics shown beside an example under `src/examples/` come from running
 * `@kirana-style/compiler` over the same file the page renders live, never from prose. Also
 * highlights the homepage's `showcase/` snippets.
 *
 * Needs the native engine (`vp run engine`); the output is committed, so `dev` and `typecheck` do not.
 */
import { readdir, readFile, writeFile } from "node:fs/promises"
import { basename, join, relative } from "node:path"
import { Driver } from "@kirana-style/compiler"

import {
  highlightSource,
  highlightTerminal,
} from "@workspace/docs-core/highlight.ts"

const root = new URL("..", import.meta.url).pathname
const examplesDir = join(root, "src/examples")
const out = join(root, "src/generated/examples.gen.ts")
const check = process.argv.includes("--check")

/** `.kirana-placeholder` is the stylesheet entry the adapter replaces; it is not a rule of the example. */
const PLACEHOLDER = /\.kirana-placeholder\s*\{[^}]*\}\s*/g
/** A rule's leading class, conditional ones too (`.k1:where(:hover)`, `.k2::before`). */
const RULE = /^\s*\.([A-Za-z][\w-]*)(?=[\s,{:[])/gm

const files = (await readdir(examplesDir))
  .filter((name) => name.endsWith(".tsx"))
  .sort()

type Compiled = {
  name: string
  source: string
  sourceHtml: string
  css: string
  cssHtml: string
  classNames: string[]
  diagnostics: {
    code: string
    name: string
    severity: string
    message: string
    line: number
  }[]
}

const compiled: Compiled[] = []
const problems: string[] = []

for (const file of files) {
  const name = basename(file, ".tsx")
  const path = join(examplesDir, file)
  const source = await readFile(path, "utf8")

  // One session per example: `stylesheet()` is then this example's CSS alone.
  const driver = await Driver.create({ root })
  const result = driver.transform(path, source)
  const css = driver.stylesheet(false).replace(PLACEHOLDER, "").trim()
  const diagnostics = [...result.diagnostics, ...driver.diagnostics()]

  for (const diagnostic of diagnostics) {
    if (diagnostic.severity === "error" || diagnostic.severity === "warning") {
      problems.push(
        `${relative(root, path)}: ${diagnostic.severity} ${diagnostic.name}: ${diagnostic.message}`
      )
    }
  }
  if (!css) problems.push(`${relative(root, path)}: compiled to no CSS`)

  compiled.push({
    name,
    source,
    sourceHtml: highlightSource(source, "tsx"),
    css,
    cssHtml: highlightSource(css, "css"),
    classNames: [
      ...new Set([...css.matchAll(RULE)].map((match) => match[1]!)),
    ].sort(),
    diagnostics: diagnostics.map((diagnostic) => ({
      code: diagnostic.code,
      name: diagnostic.name,
      severity: diagnostic.severity,
      message: diagnostic.message,
      line: diagnostic.span.start,
    })),
  })
}

if (problems.length > 0) {
  console.error(`Examples must compile clean:\n  ${problems.join("\n  ")}`)
  process.exit(1)
}

const text = `// @generated by scripts/generate-examples.ts. Do not edit.
//
// Every field below came out of the compiler in this repository. Run
// \`bun run generate:examples\` after changing a file in src/examples/.
import type { CompiledExample } from "@/lib/examples"

export const EXAMPLES: Readonly<Record<string, CompiledExample>> = ${JSON.stringify(
  Object.fromEntries(compiled.map((example) => [example.name, example])),
  null,
  2
)}
`

// The homepage's snippets under `showcase/`, named `<name>.<lang>.txt` so no
// tool treats them as modules. Each is highlighted; the `diagnostic*` ones are
// compiled too, so the error the homepage shows is the one the compiler reports.
const showcaseDir = join(root, "showcase")
const showcase = []
for (const file of (await readdir(showcaseDir)).sort()) {
  const match = /^(.+)\.(tsx|css|bash)\.txt$/.exec(file)
  if (!match) continue
  const [, name, lang] = match as unknown as [string, string, string]
  const source = await readFile(join(showcaseDir, file), "utf8")
  let diagnostics: {
    code: string
    name: string
    message: string
    help: string[]
  }[] = []
  if (name.startsWith("diagnostic")) {
    const driver = await Driver.create({ root })
    const result = driver.transform(join(showcaseDir, `${name}.tsx`), source)
    driver.stylesheet(false)
    diagnostics = [...result.diagnostics, ...driver.diagnostics()].map(
      (diagnostic) => ({
        code: diagnostic.code,
        name: diagnostic.name,
        message: diagnostic.message,
        help: [...diagnostic.help],
      })
    )
  }
  if (name.startsWith("diagnostic") && diagnostics.length === 0) {
    problems.push(`showcase/${file}: meant to fail, and compiled clean`)
  }
  showcase.push({
    name,
    lang,
    source,
    // Shell snippets are drawn as terminals, prompt and all, as docs `bash` blocks are.
    html:
      lang === "bash"
        ? highlightTerminal(source, true)
        : highlightSource(source, lang),
    diagnostics,
  })
}

if (problems.length > 0) {
  console.error(problems.join("\n"))
  process.exit(1)
}

const showcaseOut = join(root, "src/generated/showcase.gen.ts")
const showcaseText = `// @generated by scripts/generate-examples.ts from showcase/. Do not edit.
import type { ShowcaseSnippet } from "@/lib/examples"

export const SHOWCASE: Readonly<Record<string, ShowcaseSnippet>> = ${JSON.stringify(
  Object.fromEntries(showcase.map((snippet) => [snippet.name, snippet])),
  null,
  2
)}
`

let stale = false
for (const [path, body, label] of [
  [out, text, `examples: ${compiled.length}`],
  [showcaseOut, showcaseText, `showcase: ${showcase.length}`],
] as const) {
  const current = await readFile(path, "utf8").catch(() => undefined)
  if (current === body) {
    console.log(`${label} up to date`)
  } else if (check) {
    console.error(
      `${relative(root, path)} is stale. Run \`bun run generate:examples\`.`
    )
    stale = true
  } else {
    await writeFile(path, body)
    console.log(`${label} written`)
  }
}
if (stale) process.exit(1)
