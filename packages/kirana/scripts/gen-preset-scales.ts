/**
 * Generates `npm/preset-scales/src/scales.ts` from Tailwind CSS's `theme.css`
 * (MIT, Copyright (c) Tailwind Labs, Inc.; the notice ships in the package README).
 * Only design values are copied: palette, spacing steps, type ramp, radii, shadows, blur,
 * easing, breakpoints and container sizes, plus the `duration-*` and `z-*` utility steps
 * (KRN-TOK-009, D-010).
 *
 *   bun run gen:preset-scales
 */
import { spawnSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import path from "node:path"

const require = createRequire(import.meta.url)
const themePath = path.join(
  path.dirname(require.resolve("tailwindcss/package.json")),
  "theme.css"
)
const version = JSON.parse(
  readFileSync(path.join(path.dirname(themePath), "package.json"), "utf8")
).version
const theme = readFileSync(themePath, "utf8")

const variables = new Map<string, string>()
for (const match of theme.matchAll(/^\s*--([a-z0-9-]+):\s*([^;]+);/gm)) {
  variables.set(match[1]!, match[2]!.replace(/\s+/g, " ").trim())
}
const group = (
  prefix: string,
  rename: (key: string) => string = (key) => key,
  /** A longer prefix that names another group: `text-shadow-` inside `text-`. */
  except?: string
) =>
  Object.fromEntries(
    [...variables]
      .filter(
        ([name]) =>
          name.startsWith(prefix) &&
          !name.includes("--") &&
          !(except && name.startsWith(except))
      )
      .map(([name, value]) => [rename(name.slice(prefix.length)), value])
  )

const palette: Record<string, Record<string, string>> = {}
for (const [name, value] of variables) {
  const match = name.match(/^color-([a-z]+)-(\d+)$/)
  if (match) (palette[match[1]!] ??= {})[match[2]!] = value
}
const colors = {
  ...palette,
  black: variables.get("color-black")!,
  white: variables.get("color-white")!,
}

const unit = Number(variables.get("spacing")!.replace("rem", ""))
const steps = [
  0, 0.5, 1, 1.5, 2, 2.5, 3, 3.5, 4, 5, 6, 7, 8, 9, 10, 11, 12, 14, 16, 20, 24,
  28, 32, 36, 40, 44, 48, 52, 56, 60, 64, 72, 80, 96,
]
const space: Record<string, string> = { px: "1px" }
for (const step of steps)
  space[String(step)] = step === 0 ? "0px" : `${+(step * unit).toFixed(4)}rem`

const camel = (key: string) =>
  key.replace(/-([a-z0-9])/g, (_, letter: string) => letter.toUpperCase())
// `--text-shadow-*` are text shadows, not font sizes: Tailwind's `text-` prefix holds both.
const fontSize = group("text-", undefined, "text-shadow-")
const lineHeight = Object.fromEntries(
  [...variables]
    .filter(([name]) => /^text-[a-z0-9]+--line-height$/.test(name))
    .map(([name, value]) => [name.slice(5, -13), value])
)

const groups: [string, string, unknown][] = [
  [
    "color",
    "The palette: 26 hues × 11 steps, plus black and white, in oklch().",
    colors,
  ],
  ["space", "The spacing scale, in rem.", space],
  ["fontFamily", "Font stacks.", group("font-", camel)],
  ["fontSize", "The type ramp.", fontSize],
  ["lineHeight", "The line height paired with each fontSize step.", lineHeight],
  ["fontWeight", "Named weights.", group("font-weight-")],
  ["letterSpacing", "Tracking.", group("tracking-")],
  ["leading", "Named line heights.", group("leading-")],
  ["radius", "Corner radii.", group("radius-")],
  ["shadow", "Box shadows.", group("shadow-")],
  ["textShadow", "Text shadows (`text-shadow-*`).", group("text-shadow-")],
  ["blur", "Blur radii for filter and backdrop-filter.", group("blur-")],
  ["easing", "Timing functions.", group("ease-", camel)],
  ["screen", "Breakpoint widths.", group("breakpoint-")],
  ["containerSize", "Container widths.", group("container-")],
  // Not theme variables: Tailwind's `duration-*` and `z-*` utilities take bare numbers.
  [
    "duration",
    "Transition and animation durations (`duration-*`).",
    Object.fromEntries(
      [0, 75, 100, 150, 200, 300, 500, 700, 1000].map((ms) => [
        String(ms),
        ms === 0 ? "0s" : `${ms}ms`,
      ])
    ),
  ],
  [
    "zIndex",
    "Stacking levels (`z-*`).",
    {
      ...Object.fromEntries(
        [0, 10, 20, 30, 40, 50].map((level) => [String(level), String(level)])
      ),
      auto: "auto",
    },
  ],
]
const fontFamilies = groups.find(
  ([name]) => name === "fontFamily"
)![2] as Record<string, string>
for (const key of Object.keys(fontFamilies)) {
  if (key.startsWith("weight")) delete fontFamilies[key]
}

const lines = [
  `// @generated by scripts/gen-preset-scales.ts from tailwindcss ${version} theme.css`,
  "// (MIT, Copyright (c) Tailwind Labs, Inc.). Do not edit.",
  "",
  'import { defineTokens } from "@kirana-style/core"',
  "",
]
for (const [name, doc, values] of groups) {
  lines.push(
    `/** ${doc} */`,
    `export const ${name} = defineTokens(${JSON.stringify(name)}, ${JSON.stringify(values, null, 2)})`,
    ""
  )
}
const output = path.join(
  import.meta.dirname,
  "../npm/preset-scales/src/scales.ts"
)
writeFileSync(output, lines.join("\n"))
// Formatted with the repository's formatter so the CI freshness check compares like with like.
const format = spawnSync("bunx", ["oxfmt", output], {
  cwd: path.join(import.meta.dirname, "../../.."),
  stdio: "inherit",
})
if (format.status !== 0) throw new Error("oxfmt failed")
console.log(`${groups.length} token groups from tailwindcss ${version}`)
