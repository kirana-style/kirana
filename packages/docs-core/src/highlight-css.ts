/**
 * The stylesheet for highlighted code. The scheme lives in `color-scheme` on
 * `<html>`, not a `.dark` class as `createThemeCss()` expects, so every colour is
 * one `light-dark()` pair. It is global CSS because the markup belongs to the
 * highlighter; it sits in the `base` layer, scoped to code blocks and inline code.
 */
import { githubDarkTheme } from "@tanstack/highlight/themes/github-dark"
import { githubLightTheme } from "@tanstack/highlight/themes/github-light"

type Theme = {
  background: string
  foreground: string
  tokens: Record<string, string>
}

const ROOT = '[data-slot="code-block-source"]'
/** Where token colours apply: code blocks, and inline code in prose and tables. */
const SCOPE = `${ROOT}, [data-slot="code-inline"]`
/** Every scope that colours `kind`, as one selector list. */
const within = (kind: string) =>
  SCOPE.split(", ")
    .map((scope) => `${scope} .th-${kind}`)
    .join(", ")

export function highlightCss(): string {
  const light = githubLightTheme as Theme
  const dark = githubDarkTheme as Theme
  const names = Object.keys(light.tokens).sort()
  const missing = names.filter((name) => !dark.tokens[name])
  if (missing.length > 0) {
    throw new Error(`the dark theme has no colour for: ${missing.join(", ")}`)
  }

  const variables = names
    .map(
      (name) =>
        `    --th-${name}: light-dark(${light.tokens[name]}, ${dark.tokens[name]});`
    )
    .join("\n")
  // `th-token` is the base colour, and every token span carries it beside its
  // specific class. Equal specificity means source order decides, so it goes
  // first: alphabetical order would put it after `th-string` and repaint every
  // token in the default colour.
  const rule = (name: string) =>
    `  ${within(name)} {\n    color: var(--th-${name});\n  }`
  const rules = [
    rule("token"),
    ...names.filter((name) => name !== "token").map(rule),
  ].join("\n\n")

  return `/*
 * @generated by scripts/generate-content.ts from @tanstack/highlight's GitHub
 * themes. Do not edit; run \`bun run generate:content\`.
 */
@layer base {
  ${SCOPE} {
${variables}
    color: light-dark(${light.foreground}, ${dark.foreground});
  }

${rules}

  /* A terminal's prompt, and the part of an output line a terminal prints bold. */
  ${within("prompt")} {
    color: var(--th-type);
    user-select: none;
  }

  ${within("strong")} {
    font-weight: 600;
  }

  ${ROOT} .th-line {
    display: inline-block;
    width: 100%;
  }

  /* Line numbers, opted into with data-line-numbers on the <pre>. */
  ${ROOT}[data-line-numbers] code {
    counter-reset: th-line;
  }

  ${ROOT}[data-line-numbers] .th-line::before {
    counter-increment: th-line;
    content: counter(th-line);
    display: inline-block;
    width: 2ch;
    margin-inline-end: 1.25ch;
    text-align: end;
    color: light-dark(${light.foreground}66, ${dark.foreground}55);
    user-select: none;
  }

  ${ROOT} .th-line--highlighted {
    background-color: light-dark(${light.tokens.literal}14, ${dark.tokens.literal}26);
    box-shadow: inset 2px 0 0 0 light-dark(${light.tokens.literal}, ${dark.tokens.literal});
  }
}
`
}
